import '@testing-library/jest-dom';
import { vi } from 'vitest';

// Node 26 exposes process-level storage accessors which shadow jsdom's storage
// globals and return undefined unless --localstorage-file is supplied. Keep the
// test environment deterministic with isolated, browser-compatible stores.
const createMemoryStorage = (): Storage => {
  const values = new Map<string, string>();

  return {
    get length() {
      return values.size;
    },
    clear() {
      values.clear();
    },
    getItem(key) {
      return values.get(String(key)) ?? null;
    },
    key(index) {
      return Array.from(values.keys())[index] ?? null;
    },
    removeItem(key) {
      values.delete(String(key));
    },
    setItem(key, value) {
      values.set(String(key), String(value));
    },
  };
};

Object.defineProperties(globalThis, {
  localStorage: {
    configurable: true,
    value: createMemoryStorage(),
  },
  sessionStorage: {
    configurable: true,
    value: createMemoryStorage(),
  },
});

// Mock window.matchMedia
Object.defineProperty(window, 'matchMedia', {
  writable: true,
  value: vi.fn().mockImplementation((query) => ({
    matches: false,
    media: query,
    onchange: null,
    addListener: vi.fn(),
    removeListener: vi.fn(),
    addEventListener: vi.fn(),
    removeEventListener: vi.fn(),
    dispatchEvent: vi.fn(),
  })),
});
